export function getExecutionProgramIcon(programId?: string | null): EntityIcon | null {
	const slug = EXECUTION_PROGRAM_ICON_SLUGS[programId || ''];
	return slug ? entityIcon(slug) : null;
}

/** Brand for a program id the feed should show. The live API can still say OTHER. */
export function executionProgramBrand(
	programId?: string | null
): { slug: EntityIconSlug; name: string } | null {
	const icon = getExecutionProgramIcon(programId);
	if (!icon) return null;
	return {
		slug: icon.slug,
		name: EXECUTION_BRAND_NAME[icon.slug] ?? icon.slug.replaceAll('-', ' ').toUpperCase()
	};
}

function entityIcon(slug: EntityIconSlug): EntityIcon {
	return {
		slug,
		url: `/entity-icons/${slug}.${VECTOR_ENTITY_ICON_SLUGS.has(slug) ? 'svg' : 'webp'}`
	};
}
