const matchRules = [...ENTITY_ICON_SLUGS]
	.map((slug) => [slug.replaceAll('-', ''), slug] as const)
	.sort((left, right) => right[0].length - left[0].length);

function normalize(value: string): string {
	return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function resolveCandidate(candidate: string): EntityIconSlug | null {
	if (aliases[candidate]) return aliases[candidate];
	if (knownSlugs.has(candidate)) return candidate as EntityIconSlug;
	const compact = candidate.replaceAll('-', '');
	if (aliases[compact]) return aliases[compact];
	if (knownSlugs.has(compact)) return compact as EntityIconSlug;
	return null;
}

export function getEntityIcon(label?: string | null): { slug: EntityIconSlug; url: string } | null {
	const normalized = normalize(label || '');
	if (!normalized) return null;
	let resolved = resolveCandidate(normalized);
	const parts = normalized.split('-');
	while (!resolved && parts.length > 1 && removableSuffixes.has(parts.at(-1) || '')) {
		parts.pop();
		resolved = resolveCandidate(parts.join('-'));
	}
	if (!resolved) {
		const compact = normalized.replaceAll('-', '');
		resolved = matchRules.find(([needle]) => compact.includes(needle))?.[1] ?? null;
	}
	if (!resolved) return null;
	return entityIcon(resolved);
}

