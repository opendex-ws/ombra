import fs from 'node:fs';
import { expect, test } from 'vitest';

// The generated v2 client must carry the backend's additive RH schema. The
// client is regenerated from backend opendex.v2.openapi.yaml with
// `pnpm exec openapi-typescript <spec> -o src/lib/api/v2.d.ts`; `pnpm check`
// (run by the same CI job) proves the app still type-checks against it.
const client = fs.readFileSync('src/lib/api/v2.d.ts', 'utf8');
const schemas = client.slice(client.indexOf('export interface components'));

test('f0_happy', () => {
	expect(client.startsWith('/**\n * This file was auto-generated by openapi-typescript.')).toBe(true);
	for (const name of ['executionProtocol', 'launchOrigin', 'poolAssessment', 'capability']) {
		expect(schemas).toMatch(new RegExp(`\\b${name}\\??:`));
	}
});
test('f0_negative_a', () => {
	for (const name of ['bondingCurve', 'hook', 'currentVenues', 'launchOrigins', 'poolHookPresence', 'poolReviewStates']) {
		expect(schemas).toContain(name);
	}
});
test('f0_negative_b', () => {
	// Every executionProtocol union carries the new physical families and an
	// explicit UNKNOWN, so unknown venues never collapse into a known one.
	const unions = [...schemas.matchAll(/executionProtocol\??: \(([^)]*)\)/g)].map((m) => m[1]);
	expect(unions.length).toBeGreaterThan(0);
	for (const union of unions) {
		for (const value of ['"SLIPSTREAM"', '"METRIC_V1"', '"UNKNOWN"', '"UNISWAP_V4"']) expect(union).toContain(value);
	}
});
